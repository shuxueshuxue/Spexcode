// Generates one deliberately-wrong stub per frozen decision, each a MINIMAL edit away from the
// canonical engine.mjs. Running the same conformance vectors against a stub makes our own assertion
// fire, which is what distinguishes a real counter-example from a missing-file failure.
//
//   node stubs/build.mjs           regenerate the stubs
//   node stubs/run.mjs             run the vectors against each and print which assertions fired
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const source = readFileSync(join(here, '..', 'engine.mjs'), 'utf8')

const apply = (text, edits) => {
  let out = text
  for (const [from, to] of edits) {
    if (!out.includes(from)) throw new Error(`stub edit no longer matches engine.mjs:\n${from.slice(0, 120)}`)
    out = out.replaceAll(from, to)
  }
  return out
}

