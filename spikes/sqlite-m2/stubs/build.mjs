if (import.meta.url === `file://${process.argv[1]}`) {
  for (const flip of FLIPS) {
    const banner = `// DELIBERATELY WRONG -- generated by stubs/build.mjs, do not edit and do not import from
// anything but the conformance vectors.
// Flip: ${flip.name}
// Frozen claim it violates: ${flip.claim}
// This file differs from engine.mjs in exactly ${flip.edits.length} place(s).
`
    const path = join(here, `${flip.name}.mjs`)
    writeFileSync(path, banner + apply(source, flip.edits))
    console.log(`wrote ${path}`)
  }
}
